#!/usr/bin/env python3
"""
bundle.py — flatten a test/bench into ONE self-contained .cu for `colab-push`.

    python3 scripts/bundle.py tests/test_matmul.cu  ->  build/test_matmul.cu

Rules:
  * `#include "foo.cuh"` is inlined once (respects #pragma once semantics).
  * `#include <...>` system headers are left alone.
  * Convention: if include/foo.cuh is inlined and src/foo.cu exists,
    src/foo.cu is appended too (header = interface, src = implementation).
  * `#line` markers are emitted, so nvcc errors on Colab still point to the
    ORIGINAL file and line (e.g. "src/matmul.cu(42): error ...").
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEARCH = [ROOT / "include", ROOT / "src", ROOT / "tests", ROOT / "benchmarks"]
INCLUDE_RE = re.compile(r'^\s*#\s*include\s+"([^"]+)"')
PRAGMA_ONCE_RE = re.compile(r"^\s*#\s*pragma\s+once")

seen: set[Path] = set()
pending_impl: list[Path] = []


def resolve(name: str, current: Path) -> Path:
    for d in [current.parent, *SEARCH]:
        p = (d / name).resolve()
        if p.is_file():
            return p
    sys.exit(f"bundle.py: cannot find \"{name}\" (included from {current})")


def emit(path: Path, out: list[str]) -> None:
    if path in seen:
        return
    seen.add(path)

    rel = path.relative_to(ROOT).as_posix()
    if path.suffix == ".cuh":
        impl = ROOT / "src" / (path.stem + ".cu")
        if impl.is_file():
            pending_impl.append(impl.resolve())

    out.append(f'#line 1 "{rel}"\n')
    for lineno, line in enumerate(path.read_text().splitlines(keepends=True), 1):
        if PRAGMA_ONCE_RE.match(line):
            out.append("\n")
            continue
        m = INCLUDE_RE.match(line)
        if m:
            emit(resolve(m.group(1), path), out)
            out.append(f'#line {lineno + 1} "{rel}"\n')
        else:
            out.append(line)
    if not out[-1].endswith("\n"):
        out.append("\n")


def main() -> None:
    if len(sys.argv) < 2:
        sys.exit("usage: bundle.py <entry.cu> [out.cu]")
    entry = Path(sys.argv[1]).resolve()
    out_path = (Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "build" / entry.name).resolve()

    out = [f"// AUTO-GENERATED by scripts/bundle.py from {entry.relative_to(ROOT)} — do not edit.\n"]
    emit(entry, out)
    while pending_impl:  # implementations may pull in more headers -> more impls
        emit(pending_impl.pop(0), out)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("".join(out))
    files = ", ".join(sorted(p.relative_to(ROOT).as_posix() for p in seen))
    print(f"[bundle] {out_path.relative_to(ROOT)}  <=  {files}")


if __name__ == "__main__":
    main()
